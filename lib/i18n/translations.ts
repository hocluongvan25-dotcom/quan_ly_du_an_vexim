export function getTranslation(locale: Locale, key: string, fallback?: string): string {
  const keys = key.split(".");
  let value: any = translations[locale];
  for (const k of keys) {
    if (value && typeof value === "object" && k in value) {
      value = value[k];
    } else {
      // fallback to English
      let enValue: any = translations.en;
      for (const ek of keys) {
        if (enValue && typeof enValue === "object" && ek in enValue) {
          enValue = enValue[ek];
        } else {
          return fallback || key;
        }
      }
      return typeof enValue === "string" ? enValue : fallback || key;
    }
  }
  return typeof value === "string" ? value : fallback || key;
}

export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  let result = template;
  for (const [key, value] of Object.entries(params)) {
    result = result.replace(new RegExp(`{${key}}`, "g"), String(value));
  }
  return result;
}
